export function initI18n(onChange) {
  const textNodes = [];
  const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
  while (walker.nextNode()) {
    const node = walker.currentNode;
    if (
      !node.parentElement.closest("script,style,textarea,pre,code") &&
      Object.hasOwn(translations, normalize(node.nodeValue))
    )
      textNodes.push({ node, original: node.nodeValue });
  }
  const attributes = [];
  for (const node of document.querySelectorAll(
    "[placeholder],[aria-label],[title]",
  ))
    for (const name of ["placeholder", "aria-label", "title"]) {
      const original = node.getAttribute(name);
      if (original && translations[normalize(original)])
        attributes.push({ node, name, original });
    }
  const originalTitle = document.title;
  const right = document.createElement("div");
  right.className = "top-actions";
  const toggle = document.createElement("button");
  toggle.id = "language-toggle";
  toggle.className = "button small";
  toggle.type = "button";
  const badge = document.querySelector(".topbar .badge");
  badge.before(right);
  right.append(toggle, badge);
  function apply() {
    document.documentElement.lang = locale === "zh" ? "zh-CN" : "en";
    document.title = t(originalTitle);
    for (const entry of textNodes)
      if (entry.node.isConnected) entry.node.nodeValue = t(entry.original);
    for (const entry of attributes)
      entry.node.setAttribute(entry.name, t(entry.original));
    toggle.textContent = locale === "zh" ? "English" : "中文";
    toggle.setAttribute(
      "aria-label",
      locale === "zh" ? "Switch to English" : "切换为中文",
    );
    onChange?.();
  }
  toggle.addEventListener("click", () => {
    locale = locale === "zh" ? "en" : "zh";
    try {
      localStorage.setItem(storageKey, locale);
    } catch {}
    apply();
  });
  apply();
}
